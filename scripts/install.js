#!/usr/bin/env node

/*
 * Copies the files under assets/ into the host storefront at the same relative paths.
 *
 * Edge Delivery serves code from git, so the storefront must commit the copies;
 * node_modules does not exist at runtime.
 *
 * Every copied file starts with a header holding the hash of the content we wrote.
 * On the next install a file is only replaced when that hash still matches, i.e. nobody
 * edited it in the storefront. Edited files are skipped with a warning unless --force.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const PKG = require('../package.json');

const ASSETS = path.resolve(__dirname, '..', 'assets');
const MARKER_REL = path.join('scripts', 'initializers', 'index.js');
const LOG_PREFIX = `[${PKG.name}]`;
// Kept under the boilerplate's 100-character max-len so the copies pass the storefront's lint.
// The blank line after the header keeps a file that opens with its own comment lint-clean
// (stylelint's comment-empty-line-before).
const HEADER_RE = /^\/\*\n \* Generated by (\S+)@(\S+) - do not edit\.\n \* sha256:([0-9a-f]{64})\n \*\/\n\n/;

const log = (message) => console.log(`${LOG_PREFIX} ${message}`);
const warn = (message) => console.warn(`${LOG_PREFIX} ${message}`);

const sha256 = (text) => crypto.createHash('sha256').update(text).digest('hex');

function withHeader(body) {
  return `/*\n * Generated by ${PKG.name}@${PKG.version} - do not edit.\n * sha256:${sha256(body)}\n */\n\n${body}`;
}

/** 'missing' | 'ours' (unchanged since we wrote it) | 'modified' (edited, or not ours). */
function classify(dest) {
  if (!fs.existsSync(dest)) return 'missing';
  const content = fs.readFileSync(dest, 'utf8');
  const match = content.match(HEADER_RE);
  if (!match || match[1] !== PKG.name) return 'modified';
  return sha256(content.slice(match[0].length)) === match[3] ? 'ours' : 'modified';
}

function listAssets(dir = ASSETS) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? listAssets(full) : [path.relative(ASSETS, full)];
  });
}

function resolveProjectRoot(candidates) {
  return candidates.find((dir) => dir && fs.existsSync(path.join(dir, MARKER_REL))) || null;
}

/** Returns { written, unchanged, skipped } lists of relative paths. */
function install(projectRoot, { force = false } = {}) {
  const report = { written: [], unchanged: [], skipped: [] };

  listAssets().forEach((rel) => {
    const dest = path.join(projectRoot, rel);
    const next = withHeader(fs.readFileSync(path.join(ASSETS, rel), 'utf8'));
    const state = classify(dest);

    if (state === 'modified' && !force) {
      report.skipped.push(rel);
      return;
    }
    if (state === 'ours' && fs.readFileSync(dest, 'utf8') === next) {
      report.unchanged.push(rel);
      return;
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, next);
    report.written.push(rel);
  });

  return report;
}

function main(argv) {
  const force = argv.includes('--force');
  const projectRoot = resolveProjectRoot([
    process.env.INIT_CWD,
    process.cwd(),
    path.resolve(__dirname, '..', '..', '..', '..'),
  ]);

  if (!projectRoot) {
    warn(
      `could not find ${MARKER_REL}, so this is not an aem-boilerplate-commerce storefront `
      + 'and nothing was written. Run "npx eds-vertex-tax" from the storefront root.',
    );
    return;
  }

  const { written, unchanged, skipped } = install(projectRoot, { force });
  written.forEach((rel) => log(`wrote ${rel}`));
  if (unchanged.length) log(`${unchanged.length} file(s) already up to date`);
  skipped.forEach((rel) => warn(
    `skipped ${rel}: it was edited in the storefront. Move the change into the package, `
    + 'or run "npx eds-vertex-tax --force" to overwrite it.',
  ));
  if (written.length) log('done. Commit the written files, because Edge Delivery serves code from git.');
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    // Never fail the storefront's npm install over this step.
    warn(`install step failed: ${error && error.message}`);
    warn('the storefront was left as it was; run "npx eds-vertex-tax" to retry.');
  }
}

module.exports = {
  classify,
  install,
  listAssets,
  resolveProjectRoot,
  withHeader,
};
